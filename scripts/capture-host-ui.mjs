import { createRequire } from 'node:module';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require('C:/Users/ccf/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = resolve(import.meta.dirname, '..');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const url = (await readFile(join(root, 'artifacts/product-host/capture-url.txt'), 'utf8')).trim();
  await page.goto(url);
  await page.waitForSelector('[data-dsh-better-sidebar], [contenteditable]', { timeout: 90000 });
  const workspace = page.getByText('默认工作区', { exact: true });
  if (await workspace.count()) await workspace.first().click();
  await page.waitForTimeout(1000);
  const proceed = page.getByRole('button', { name: '继续', exact: true });
  if (await proceed.isVisible().catch(() => false)) await proceed.click();
  const later = page.getByRole('button', { name: '稍后配置', exact: true });
  if (await later.isVisible().catch(() => false)) await later.click();
  await page.waitForTimeout(700);
  const dialogClose = page.getByRole('dialog').getByRole('button', { name: /关闭|Close/ });
  if (await dialogClose.count()) await dialogClose.first().click();
  await page.keyboard.press('Escape');
  const side = page.getByRole('button', { name: '打开右侧边栏', exact: true });
  if (await side.isVisible().catch(() => false)) await side.click();
  await page.waitForTimeout(700);
  const science = page.getByText('科研工作台', { exact: true });
  if (await science.count()) await science.first().click();
  await page.waitForTimeout(700);
  await page.getByRole('button', { name: '全屏', exact: true }).click();
  await page.waitForTimeout(500);
  await mkdir(join(root, 'design/generated'), { recursive: true });
  await page.screenshot({ path: join(root, 'design/generated/app-workspace.png') });
  await page.getByRole('button', { name: /^ImageJ 图像/ }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: join(root, 'design/generated/imaging.png') });
  await writeFile(join(root, 'design/generated/capture-receipt.json'), JSON.stringify({ version: '8.4.0', source: 'Actual shipped 8.4.0 Host runtime and offline plugins, regular Node, isolated empty profile, no project or credentials', capturedAt: new Date().toISOString(), views: { 'app-workspace.png': 'Research workbench, full panel', 'imaging.png': 'ImageJ file selection interface, no loaded scientific data' } }, null, 2));
  console.log('IMAGES', await page.locator('img').evaluateAll(nodes => nodes.map(n => ({ src: n.getAttribute('src'), ok: n.complete && n.naturalWidth > 0 }))));
  console.log((await page.locator('body').innerText()).slice(0, 14000));
  await mkdir(join(root, 'design/generated'), { recursive: true });
  await page.screenshot({ path: join(root, 'artifacts/host-inspect.png') });
  await writeFile(join(root, 'artifacts/host-buttons.json'), JSON.stringify(await page.getByRole('button').evaluateAll(nodes => nodes.map(node => ({ label: node.getAttribute('aria-label'), text: node.textContent, title: node.getAttribute('title') }))), null, 2));
} finally { await browser.close(); }
